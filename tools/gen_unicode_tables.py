#!/usr/bin/env python3
"""Generates src/core/unicode_tables.inc, the Unicode data the tokenizers need (src/core/unicode.cpp):

* the general category of every code point, as runs (\\p{L}, \\p{Lu}, \\p{N}, ... in pre-tokenizer patterns);
* canonical combining classes, canonical decompositions and which of them compose again (NFC normalization,
  which the Qwen tokenizers apply before splitting);
* the code points that may change under NFC, so text made only of others skips normalization;
* the non-ASCII code points whose simple case folding is an ASCII letter (case-insensitive groups such as
  (?i:'s) also match "'ſ"), which is all case folding the pre-tokenizer patterns need.

The data comes from the Python interpreter's unicodedata module; the header records its Unicode version.
Regenerate when updating Unicode (with a Python whose unicodedata has that version):

    python3 tools/gen_unicode_tables.py > src/core/unicode_tables.inc
"""
import unicodedata

# Order matters: src/core/unicode.h enum Category lists the same names in the same order.
CATEGORIES = ["Lu", "Ll", "Lt", "Lm", "Lo", "Mn", "Mc", "Me", "Nd", "Nl", "No", "Pc", "Pd", "Ps", "Pe", "Pi", "Pf",
              "Po", "Sm", "Sc", "Sk", "So", "Zs", "Zl", "Zp", "Cc", "Cf", "Cs", "Co", "Cn"]
MAX = 0x110000
# Hangul syllables compose and decompose algorithmically (src/core/unicode.cpp), not through the table.
HANGUL_FIRST, HANGUL_LAST = 0xAC00, 0xD7A3


def runs(value_of):
    """[(first code point, value)] where the value changes; the last run ends at U+10FFFF."""
    out, last = [], None
    for cp in range(MAX):
        v = value_of(cp)
        if v != last:
            out.append((cp, v))
            last = v
    return out


def emit_words(name, words, comment, per_line=8):
    print(f"// {comment}: {len(words)} entries")
    print(f"constexpr uint32_t {name}[] = {{")
    for i in range(0, len(words), per_line):
        print("    " + " ".join(f"0x{w:X}," for w in words[i:i + per_line]))
    print("};")


def main():
    print(f"// Generated by tools/gen_unicode_tables.py (Unicode {unicodedata.unidata_version}). Do not edit.")

    cat_index = {c: i for i, c in enumerate(CATEGORIES)}
    category_runs = runs(lambda cp: cat_index[unicodedata.category(chr(cp))])
    emit_words("kCategoryRuns", [(cp << 8) | v for cp, v in category_runs],
               "general category runs, (first << 8) | category")

    ccc_runs = runs(lambda cp: unicodedata.combining(chr(cp)))
    emit_words("kCombiningClassRuns", [(cp << 8) | v for cp, v in ccc_runs],
               "canonical combining class runs, (first << 8) | class")

    # Canonical decompositions (one level; applied recursively), and whether the pair composes back:
    # a primary composite is a two-code-point decomposition of a starter that is not excluded from composition.
    decompositions = []
    pairs = set()
    for cp in range(MAX):
        if HANGUL_FIRST <= cp <= HANGUL_LAST:
            continue
        d = unicodedata.decomposition(chr(cp))
        if not d or d.startswith("<"):
            continue
        parts = [int(x, 16) for x in d.split()]
        composes = (len(parts) == 2 and unicodedata.combining(chr(cp)) == 0
                    and unicodedata.combining(chr(parts[0])) == 0
                    and unicodedata.normalize("NFC", chr(parts[0]) + chr(parts[1])) == chr(cp))
        if composes:
            pairs.add(parts[1])
        decompositions.append((cp, parts[0], parts[1] if len(parts) == 2 else 0, composes))
    words = []
    for cp, first, second, composes in decompositions:
        words += [cp | (0x80000000 if composes else 0), first, second]
    emit_words("kDecompositions", words,
               "canonical decompositions, triples {code point | 1 << 31 when it composes back, first, second or 0}", 6)

    # Code points NFC may change or combine with what precedes: not NFC on their own, a non-zero combining
    # class, or the second half of a composition (Hangul vowels and trailing consonants included).
    def maybe(cp):
        c = chr(cp)
        return (unicodedata.combining(c) != 0 or unicodedata.normalize("NFC", c) != c or cp in pairs
                or 0x1161 <= cp <= 0x1175 or 0x11A8 <= cp <= 0x11C2)
    maybe_runs = runs(lambda cp: 1 if maybe(cp) else 0)
    emit_words("kNfcMaybeRuns", [(cp << 8) | v for cp, v in maybe_runs],
               "runs of code points that NFC may change, (first << 8) | flag")

    fold_extras = []
    for cp in range(0x80, MAX):
        f = chr(cp).casefold()
        if len(f) == 1 and ord(f) < 0x80 and f.isalpha():
            fold_extras += [cp, ord(f)]
    emit_words("kAsciiFoldExtras", fold_extras, "non-ASCII code point, the ASCII letter it folds to", 4)


if __name__ == "__main__":
    main()
