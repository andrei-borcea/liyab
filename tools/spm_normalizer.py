#!/usr/bin/env python3
"""Read a SentencePiece model's normalization facts without protobuf dependencies.

The model stores its normalizer as a Darts double-array character map. GGUF
may preserve it as tokenizer.ggml.precompiled_charsmap. For a converter that
omits it, an exact map can be registered by its SHA-256 in ArchSpec.

    tools/spm_normalizer.py --model tokenizer.model --out src/core/spm_normalizer.inc

The output is data from the supplied model, with its exact digest; no model
weights or tokenizer arithmetic are copied. Keep the model ID/revision in the
surrounding documentation when registering a fallback.
"""
import argparse
import hashlib
import json
from pathlib import Path


def fields(data):
    def varint(pos):
        value = shift = 0
        while pos < len(data) and shift < 70:
            byte = data[pos]; pos += 1
            value |= (byte & 127) << shift
            if not byte & 128:
                return value, pos
            shift += 7
        raise ValueError("truncated or oversized protobuf varint")
    pos = 0
    while pos < len(data):
        tag, pos = varint(pos)
        if tag >> 3 == 0:
            raise ValueError("invalid protobuf field zero")
        wire = tag & 7
        if wire == 0:
            value, pos = varint(pos)
        else:
            if wire == 2:
                size, pos = varint(pos)
            elif wire in (1, 5):
                size = 8 if wire == 1 else 4
            else:
                raise ValueError(f"unsupported protobuf wire type {wire}")
            if size > len(data) - pos:
                raise ValueError("truncated protobuf field")
            value = data[pos:pos + size]; pos += size
        yield tag >> 3, value


def read_normalizer(path):
    raw = path if isinstance(path, bytes) else Path(path).read_bytes()
    model = dict(fields(raw))
    spec = dict(fields(model.get(3, b"")))
    charmap = spec.get(2, b"")
    user_defined = [piece[1].decode() for field, value in fields(raw) if field == 1
                    for piece in [dict(fields(value))] if piece.get(3, 1) == 4]
    return {"name": spec.get(1, b"").decode(), "map": charmap,
            "sha256": hashlib.sha256(charmap).hexdigest() if charmap else "",
            "user_defined": user_defined,
            "user_defined_sha256": hashlib.sha256(json.dumps(user_defined, ensure_ascii=False,
                separators=(",", ":")).encode()).hexdigest() if user_defined else "",
            "add_dummy_prefix": bool(spec.get(3, 1)),
            "remove_extra_whitespaces": bool(spec.get(4, 1)),
            "escape_whitespaces": bool(spec.get(5, 1))}


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--model", required=True, help="SentencePiece .model file")
    parser.add_argument("--out", help="C++ include file for the exact character map")
    args = parser.parse_args()
    spec = read_normalizer(args.model)
    print({k: (len(v) if k in ("map", "user_defined") else v) for k, v in spec.items()})
    if args.out:
        blob = spec["map"]
        lines = ["// Generated by tools/spm_normalizer.py from a SentencePiece normalizer.",
                 f'// SHA-256: {spec["sha256"]}',
                 f'constexpr std::string_view kSpmCharsmapId = "{spec["sha256"]}";',
                 "constexpr uint8_t kSpmCharsmap[] = {"]
        lines += ["    " + ", ".join(f"0x{x:02x}" for x in blob[i:i + 16]) + "," for i in range(0, len(blob), 16)]
        lines += ["};", f'constexpr std::string_view kSpmUserDefinedId = "{spec["user_defined_sha256"]}";',
                  "constexpr std::string_view kSpmUserDefined[] = {"]
        lines += ["    " + json.dumps(token, ensure_ascii=False) + "," for token in spec["user_defined"]]
        Path(args.out).write_text("\n".join(lines + ["};", ""]))


if __name__ == "__main__":
    main()
